create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, country, default_currency)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'country', null),
    coalesce(new.raw_user_meta_data->>'default_currency', 'USD')
  )
  on conflict (id) do nothing;

  insert into public.scan_ledger (user_id, delta, reason, ref_id)
  values (new.id, 10, 'signup', new.id)
  on conflict (user_id, reason, ref_id) do nothing;

  insert into public.user_categories (user_id, category_id, sort_order)
  select new.id, c.id, c.id
  from public.categories c
  where c.is_system = true
  on conflict do nothing;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_user();

