create or replace function public.refresh_receipt_search_text(target_receipt_id uuid)
returns void
language plpgsql
as $$
begin
  update public.receipts r
  set search_text =
    setweight(to_tsvector('simple', coalesce(r.merchant, '')), 'A') ||
    setweight(to_tsvector('simple', coalesce(r.notes, '')), 'B') ||
    setweight(to_tsvector('simple', coalesce((select string_agg(ri.name, ' ') from public.receipt_items ri where ri.receipt_id = r.id), '')), 'C')
  where r.id = target_receipt_id;
end;
$$;

create or replace function public.receipts_search_text_trigger()
returns trigger
language plpgsql
as $$
begin
  perform public.refresh_receipt_search_text(new.id);
  return new;
end;
$$;

create or replace function public.receipt_items_search_text_trigger()
returns trigger
language plpgsql
as $$
begin
  perform public.refresh_receipt_search_text(coalesce(new.receipt_id, old.receipt_id));
  return coalesce(new, old);
end;
$$;

