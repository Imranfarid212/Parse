/**
 * Regenerates the base64 font modules the PDF exports embed.
 *
 * The fonts are checked in as TypeScript rather than .ttf on purpose: a real
 * import is guaranteed to survive `supabase functions deploy` bundling, while a
 * sibling binary read through Deno.readFile depends on the CLI's static-file
 * handling. A font that fails to load at runtime turns every PDF export into a
 * 500, so this trades ~310 KB of repo for a failure mode that cannot happen.
 *
 * Source: googlefonts/noto-fonts, unhinted TTF, SIL OFL 1.1 (license kept
 * alongside the modules). Subset to the ranges Noto Sans actually covers that a
 * receipt is likely to contain — Latin, Latin Extended, Greek, Cyrillic,
 * punctuation and currency symbols. CJK and Indic need different font families
 * entirely and are recorded as a known gap in the decision log.
 *
 * Requires: python3 with fonttools (pip install fonttools), network access.
 * Usage: node scripts/build-export-fonts.js
 */
const { execFileSync } = require('child_process');
const fs = require('fs');
const os = require('os');
const path = require('path');

const root = path.resolve(__dirname, '..');
const outDir = path.join(root, 'supabase', 'functions', '_shared', 'exports', 'fonts');

const UNICODES = [
  'U+0020-007E', // Basic Latin
  'U+00A0-00FF', // Latin-1 Supplement
  'U+0100-017F', // Latin Extended-A
  'U+0180-024F', // Latin Extended-B
  'U+02B0-02FF', // Spacing modifiers
  'U+0300-036F', // Combining diacritics
  'U+0370-03FF', // Greek
  'U+0400-04FF', // Cyrillic
  'U+1E00-1EFF', // Latin Extended Additional (Vietnamese)
  'U+2000-206F', // General punctuation
  'U+2070-209F', // Super/subscripts
  'U+20A0-20BF', // Currency symbols
  'U+2100-214F', // Letterlike symbols
  'U+2190-2193,U+2212', // Arrows used in headers, minus sign
  'U+25A0-25FF', // Geometric shapes (bullets)
].join(',');

const WEIGHTS = [
  { name: 'Regular', file: 'noto-sans-regular.ts', constant: 'NOTO_SANS_REGULAR_BASE64' },
  { name: 'SemiBold', file: 'noto-sans-semibold.ts', constant: 'NOTO_SANS_SEMIBOLD_BASE64' },
];

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'rf-fonts-'));

for (const weight of WEIGHTS) {
  const source = path.join(tmp, `NotoSans-${weight.name}.ttf`);
  const subset = path.join(tmp, `NotoSans-${weight.name}.subset.ttf`);
  const url = `https://raw.githubusercontent.com/googlefonts/noto-fonts/main/unhinted/ttf/NotoSans/NotoSans-${weight.name}.ttf`;

  execFileSync('curl', ['-sSLf', '--max-time', '120', '-o', source, url], { stdio: 'inherit' });
  execFileSync(
    'pyftsubset',
    [
      source,
      `--output-file=${subset}`,
      `--unicodes=${UNICODES}`,
      '--layout-features=',
      '--no-hinting',
      '--desubroutinize',
      '--drop-tables+=GSUB,GPOS,GDEF',
    ],
    { stdio: 'inherit' },
  );

  const base64 = fs.readFileSync(subset).toString('base64');
  const wrapped = base64.match(/.{1,120}/g).join('\n');
  const contents = `// @ts-nocheck - Supabase Edge Functions run under Deno, outside the Expo app tsconfig.
/**
 * Noto Sans ${weight.name}, subset for receipt exports. SIL OFL 1.1 — see
 * LICENSE-NotoSans.txt in this directory.
 *
 * Generated by scripts/build-export-fonts.js. Do not hand-edit.
 */
export const ${weight.constant} = \`
${wrapped}
\`.replace(/\\s+/g, '');
`;
  fs.writeFileSync(path.join(outDir, weight.file), contents);
  console.log(`[fonts] ${weight.file} (${Math.round(base64.length / 1024)} KB base64)`);
}

fs.rmSync(tmp, { recursive: true, force: true });
